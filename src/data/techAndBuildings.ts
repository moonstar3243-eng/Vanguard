export const getUnitMatchupMultiplier = (
  attackerType: UnitType,
  defenderType: UnitType
): { mult: number; reason: string | null } => {
  const atkDef = UNITS[attackerType];
  const defDef = UNITS[defenderType];
  let mult = CLASS_DAMAGE_MATRIX[atkDef.unitClass][defDef.unitClass] ?? 1.0;
  let reason: string | null = null;

  // Fine-tuned unit-specific counter affinities
  if (
    attackerType === 'anti_tank' &&
    (defDef.unitClass === 'Armored' || defDef.unitClass === 'Vehicle')
  ) {
    mult = 1.75;
    reason = `AT Rockets vs ${defDef.unitClass} (+75%)`;
  } else if (attackerType === 'anti_tank' && defDef.unitClass === 'Infantry') {
    mult = 0.8;
    reason = 'AT Squads vs Infantry (-20%)';
  } else if (attackerType === 'interceptor' && defDef.unitClass === 'Aircraft') {
    mult = 1.85;
    reason = `Air Superiority vs ${defDef.shortName} (+85%)`;
  } else if (attackerType === 'interceptor' && defDef.unitClass === 'Armored') {
    mult = 0.78;
    reason = 'Light Cannons vs Armor (-22%)';
  } else if (
    attackerType === 'gunship' &&
    (defDef.unitClass === 'Armored' || defDef.unitClass === 'Vehicle')
  ) {
    mult = 1.75;
    reason = `Gunship Tank-Killer (+75%)`;
  } else if (attackerType === 'bomber' && (defDef.unitClass === 'Infantry' || defDef.unitClass === 'Artillery')) {
    mult = 1.6;
    reason = `Strike Bombs vs ${defDef.unitClass} (+60%)`;
  } else if (attackerType === 'bomber' && defDef.unitClass === 'Naval') {
    mult = 1.4;
    reason = 'Anti-Ship Bombs (+40%)';
  } else if (attackerType === 'destroyer' && defDef.unitClass === 'Aircraft') {
    mult = 1.65;
    reason = 'SAM Fleet Screen vs Air (+65%)';
  } else if (attackerType === 'carrier' && (defDef.unitClass === 'Naval' || defDef.unitClass === 'Armored')) {
    mult = 1.45;
    reason = `Carrier Wing Strike (+45%)`;
  } else if (mult >= 1.25) {
    reason = `${atkDef.unitClass} Counter vs ${defDef.unitClass} (+${Math.round((mult - 1) * 100)}%)`;
  } else if (mult <= 0.8) {
    reason = `${atkDef.unitClass} vs ${defDef.unitClass} (-${Math.round((1 - mult) * 100)}%)`;
  }

  return { mult, reason };
};

