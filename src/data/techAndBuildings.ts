export const getUnitEffectiveStats = (unitType: UnitType, level: number) => {
  const base = UNITS[unitType];
  const tree = UNIT_TECH_TREE[unitType];
  const safeLevel = Math.max(1, Math.min(4, Math.round(level || 1)));
  const spec = tree.levels.find((l) => l.level === safeLevel) ?? tree.levels[0];

  return {
    level: safeLevel,
    designation: spec.designation,
    attack: Math.round(base.attack * spec.atkMult),
    defense: Math.round(base.defense * spec.defMult),
    hp: Math.round(base.hp * spec.hpMult),
    move: base.move + spec.moveBonus,
    range: base.range + spec.rangeBonus,
    costDiscount: spec.costDiscount,
    upkeepDiscount: spec.upkeepDiscount,
  };
};

