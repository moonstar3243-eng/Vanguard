import React from 'react';
import { SCENARIOS } from '../data/scenarios';
import { getActivePlayerId } from '../engine/gameEngine';
import { GameState, NetIncome } from '../types/game';
import {
  AlertTriangle,
  EyeOff,
  FlaskConical,
  Flame,
  Hammer,
  HardDrive,
  Landmark,
  Megaphone,
  Radio,
  RotateCcw,
  Users,
  Volume2,
  VolumeX,
} from 'lucide-react';

interface ResourceStripProps {
  state: GameState;
  net: NetIncome;
  muted: boolean;
  onToggleMute: () => void;
  onOpenSaves: () => void;
  onResetGame: () => void;
}

const fmtDelta = (n: number) => (n >= 0 ? `+${n}` : `${n}`);

export const ResourceStrip: React.FC<ResourceStripProps> = ({
  state,
  net,
  muted,
  onToggleMute,
  onOpenSaves,
  onResetGame,
}) => {
  const activePlayerId = getActivePlayerId(state);
  const activePlayer = state.players?.[state.activePlayerIndex];
  const totalRegions = Object.keys(state.regions).length;
  const ownedCount = Object.values(state.regions).filter(
    (r) => r.ownerId === activePlayerId
  ).length;
  const controlPct = Math.round((ownedCount / totalRegions) * 100);

  const inDebt = state.resources.funds < 0;
  const mpShortage = (state.resources.manpower ?? 0) <= 4;
  const matShortage = state.resources.materials <= 0;
  const engShortage = state.resources.energy <= 0;
  const scenarioYear = SCENARIOS[state.scenarioId ?? 'modern_2026']?.yearLabel ?? '2026';

  return (
    <div className="bg-[#0D121B] border-b border-slate-800/90 px-6 py-2.5 flex flex-wrap items-center justify-between gap-4 shrink-0">
      {/* Turn, Commander, Concealment/Exposed Phase, Territory */}
      <div className="flex flex-wrap items-center gap-3 text-xs">
        <span className="font-mono tabular-nums text-slate-200 font-semibold">
          Turn {state.turn}
        </span>

        {state.gameVariant === 'BLITZ' && (
          <>
            <span className="text-slate-600" aria-hidden="true">
              ·
            </span>
            <span className="font-semibold text-amber-400">
              Blitz 2× · {scenarioYear}
            </span>
          </>
        )}

        {state.players && state.players.length > 1 && activePlayer && (
          <>
            <span className="text-slate-600" aria-hidden="true">
              ·
            </span>
            <span className="font-semibold text-white flex items-center gap-1.5">
              <span
                className="w-2.5 h-2.5 rounded-sm inline-block"
                style={{ backgroundColor: activePlayer.color }}
              />
              {activePlayer.name}
            </span>
          </>
        )}

        <span className="text-slate-600" aria-hidden="true">
          ·
        </span>

        {state.phase === 'UNDERGROUND' ? (
          <span
            className={`font-medium flex items-center gap-1.5 ${
              state.suspicion >= 75 ? 'text-amber-400' : 'text-teal-300'
            }`}
            title="Foreign countries do not know you exist until Suspicion reaches 100% or you launch your coup."
          >
            <EyeOff className="w-3.5 h-3.5" />
            Underground · Suspicion {state.suspicion}%
          </span>
        ) : (
          <span className="font-medium text-red-400 flex items-center gap-1.5">
            <Radio className="w-3.5 h-3.5" />
            Exposed Regime
          </span>
        )}

        <span className="text-slate-600" aria-hidden="true">
          ·
        </span>
        <span className="font-mono tabular-nums text-slate-300">
          Provinces:{' '}
          <strong className="text-white">
            {ownedCount}/{totalRegions}
          </strong>{' '}
          <span className="text-slate-400">({controlPct}%)</span>
        </span>
      </div>

      {/* Resource Telemetry */}
      <div className="flex flex-wrap items-center gap-4 lg:gap-5 text-xs font-mono tabular-nums">
        <div
          className="flex items-center gap-1.5"
          title={`Debt Interest: -$${net.debtInterest}/turn`}
        >
          <Landmark
            className={`w-3.5 h-3.5 ${inDebt ? 'text-red-400' : 'text-amber-400'}`}
          />
          <span className="text-slate-400">Funds</span>
          <span className={`font-semibold ${inDebt ? 'text-red-400' : 'text-white'}`}>
            ${state.resources.funds}
          </span>
          <span className={net.funds >= 0 ? 'text-emerald-400' : 'text-red-400'}>
            ({fmtDelta(net.funds)})
          </span>
          {inDebt && (
            <span className="text-[11px] font-sans font-semibold text-red-400 flex items-center gap-0.5 ml-1">
              <AlertTriangle className="w-3 h-3" /> Debt
            </span>
          )}
        </div>

        <div
          className="flex items-center gap-1.5"
          title="Recruit pool generated by population across your provinces and boosted by Conscription"
        >
          <Users
            className={`w-3.5 h-3.5 ${mpShortage ? 'text-amber-400' : 'text-rose-400'}`}
          />
          <span className="text-slate-400">Manpower</span>
          <span className={`font-semibold ${mpShortage ? 'text-amber-300' : 'text-white'}`}>
            {state.resources.manpower ?? 0}
          </span>
          <span className="text-emerald-400">({fmtDelta(net.manpower ?? 0)})</span>
          {mpShortage && (
            <span className="text-[11px] font-sans font-semibold text-amber-400 ml-0.5">
              Low
            </span>
          )}
        </div>

        <div className="flex items-center gap-1.5">
          <Hammer
            className={`w-3.5 h-3.5 ${matShortage ? 'text-red-400' : 'text-slate-300'}`}
          />
          <span className="text-slate-400">Steel</span>
          <span className={`font-semibold ${matShortage ? 'text-red-400' : 'text-white'}`}>
            {state.resources.materials}
          </span>
          <span className={net.materials >= 0 ? 'text-emerald-400' : 'text-red-400'}>
            ({fmtDelta(net.materials)})
          </span>
          {matShortage && (
            <span className="text-[11px] font-sans font-semibold text-amber-400 ml-1">
              Shortage
            </span>
          )}
        </div>

        <div className="flex items-center gap-1.5">
          <Flame
            className={`w-3.5 h-3.5 ${engShortage ? 'text-red-400' : 'text-sky-400'}`}
          />
          <span className="text-slate-400">Fuel</span>
          <span className={`font-semibold ${engShortage ? 'text-red-400' : 'text-white'}`}>
            {state.resources.energy}
          </span>
          <span className={net.energy >= 0 ? 'text-emerald-400' : 'text-red-400'}>
            ({fmtDelta(net.energy)})
          </span>
          {engShortage && (
            <span className="text-[11px] font-sans font-semibold text-amber-400 ml-1">
              Shortage
            </span>
          )}
        </div>

        <div className="flex items-center gap-1.5">
          <Megaphone className="w-3.5 h-3.5 text-purple-400" />
          <span className="text-slate-400">Influence</span>
          <span className="font-semibold text-white">{state.resources.influence}</span>
          <span className="text-emerald-400">({fmtDelta(net.influence)})</span>
        </div>

        <div className="flex items-center gap-1.5">
          <FlaskConical className="w-3.5 h-3.5 text-teal-400" />
          <span className="text-slate-400">Science</span>
          <span className="font-semibold text-white">{state.resources.science}</span>
          <span className="text-emerald-400">({fmtDelta(net.science)})</span>
        </div>
      </div>

      {/* Utility Actions */}
      <div className="flex items-center gap-2 shrink-0">
        <button
          type="button"
          onClick={onToggleMute}
          title={muted ? 'Unmute Sound' : 'Mute Sound'}
          className="p-2 text-slate-400 hover:text-white bg-[#151D29] border border-slate-800 rounded transition-colors cursor-pointer"
        >
          {muted ? <VolumeX className="w-4 h-4" /> : <Volume2 className="w-4 h-4" />}
        </button>
        <button
          type="button"
          onClick={onOpenSaves}
          className="px-3 py-1.5 text-xs font-medium text-slate-200 hover:text-white bg-[#151D29] border border-slate-800 rounded transition-colors flex items-center gap-1.5 whitespace-nowrap cursor-pointer"
        >
          <HardDrive className="w-3.5 h-3.5 text-amber-400" />
          Saves
        </button>
        <button
          type="button"
          onClick={onResetGame}
          className="px-3 py-1.5 text-xs font-medium text-slate-300 hover:text-white bg-[#151D29] border border-slate-800 rounded transition-colors flex items-center gap-1.5 whitespace-nowrap cursor-pointer"
        >
          <RotateCcw className="w-3.5 h-3.5" />
          Menu
        </button>
      </div>
    </div>
  );
};
